#!/usr/bin/env python3
"""Materialize deterministic compile workloads; --check never writes files."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent / "generated"


def error_definitions(size):
    declarations = [f'deferror ProfileError{i:03d} {{ "profile error" }}' for i in range(size)]
    return declarations + [
        '',
        'print(Error::message(ProfileError000()))',
        f'print(Error::message(ProfileError{size - 1:03d}()))',
    ]


def generic_chain(size, reverse=False):
    declarations = []
    for i in range(size):
        call = 'Monad::bind(source, next)' if i == 0 else f'stage{i - 1:03d}(source, next)'
        declarations.append(
            f'def stage{i:03d}(source: Result<$A>, next: ($A -> Result<$B>)) -> Result<$B> {{ {call} }}'
        )
    last = f'stage{size - 1:03d}'
    if reverse:
        declarations.reverse()
    return declarations + [
        '',
        f'print(inspect({last}(Ok(7), {{|x: Int| Ok(x + 1)}})))',
        f'print(inspect({last}(Ok("x"), {{|x: String| Ok(x ++ "y")}})))',
        f'print(inspect({last}(Ok(7), {{|x: Int| Ok(x + 1)}})))',
    ]


def trait_impls(size):
    lines = [f'defrecord ProfileValue{i:03d}(value: Int)' for i in range(size)]
    lines += ['', 'deftrait ProfileRead { def read(self: Self) -> Int }', '']
    for i in range(size):
        name = f'ProfileValue{i:03d}'
        lines += [f'impl ProfileRead for {name} {{', f'  def read(self: {name}) -> Int {{ self.value }}', '}']
    return lines + [
        '',
        'print(to_string(ProfileRead::read(ProfileValue000(1))))',
        f'print(to_string(ProfileRead::read(ProfileValue{size - 1:03d}(2))))',
    ]


def nominal_chain(size):
    lines = ['defrecord ProfileNode000(value: Int)']
    for i in range(1, size):
        lines.append(f'defrecord ProfileNode{i:03d}(value: ProfileNode{i - 1:03d})')
    access = 'value' + '.value' * size
    constructions = []
    for i in range(size):
        previous = '1' if i == 0 else f'node{i - 1:03d}'
        constructions.append(f'node{i:03d} = ProfileNode{i:03d}({previous})')
    return lines + [
        '',
        f'def unwrap(value: ProfileNode{size - 1:03d}) -> Int {{ {access} }}',
        '',
    ] + constructions + [f'print(to_string(unwrap(node{size - 1:03d})))']


FAMILIES = {
    'error_definitions': ((64, 128, 256), error_definitions, 'Flat Error declarations; two constructor calls at every size.'),
    'generic_chain': ((16, 32, 64), generic_chain, 'Generic call depth; three calls with Int/String/Int payloads at every size.'),
    'generic_chain_reverse': ((16, 32, 64), lambda size: generic_chain(size, reverse=True), 'Same generic chain and calls, with declarations reversed to vary propagation order.'),
    'trait_impls': ((16, 32, 64), trait_impls, 'Disjoint impl count for one trait; two dispatch sites at every size.'),
    'nominal_chain': ((16, 32, 64), nominal_chain, 'Record dependency depth; flat constructor bindings avoid parser nesting limits.'),
}


def outputs():
    for family, (sizes, render, description) in FAMILIES.items():
        for size in sizes:
            header = [
                '# Generated by ../generate.py. Edit the generator, then regenerate.',
                f'# {description}',
                f'# Scale: {size}. Manual compile workload; not a timing assertion.',
                '',
            ]
            yield ROOT / f'{family}_{size:03d}.srt', '\n'.join(header + render(size)) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='check committed inputs without writing')
    args = parser.parse_args()
    expected = dict(outputs())
    extra = set(ROOT.glob('*.srt')) - set(expected)
    if extra:
        parser.error('unexpected generated inputs: ' + ', '.join(str(p.name) for p in sorted(extra)))
    if not args.check:
        ROOT.mkdir(parents=True, exist_ok=True)
    for path, content in expected.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                parser.error(f'generated input differs: {path}')
        else:
            path.write_text(content)
    print(f'{"Checked" if args.check else "Generated"} {len(expected)} inputs')


if __name__ == '__main__':
    main()
